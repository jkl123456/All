/** 右侧批注块：小标题 + 正文 */
const block = (x, y, title, lines, color = C.blue) => {
  const out = [
    path(`M${x} ${y}h3v18h-3Z`, { stroke: 'none', fill: color, opacity: 0.9 }),
    T(title, x + 12, y + 14, { size: 14, color, anchor: 'start', weight: 700 }),
  ];
  lines.forEach((ln, i) => {
    out.push(T(ln, x + 12, y + 38 + i * 22, { size: 12.5, color: MUTED, anchor: 'start' }));
  });
  return out;
};

